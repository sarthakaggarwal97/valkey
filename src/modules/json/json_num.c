static inline int floorLog10Pow2(int e) {
    return (e * 1262611) >> 22;
}

/* floor(log10(3/4 * 2^e)) for -1074 <= e <= 971. */
static inline int floorLog10ThreeQuartersPow2(int e) {
    return (e * 1262611 - 524031) >> 22;
}

static inline int isDigit(char c) {
    return (unsigned)(c - '0') < 10;
}

/* Eight digits at a time, for the long fractions of 15 to 17 digit numbers.
 * The bytes are read as one little-endian word. */
#if defined(__BYTE_ORDER__) && __BYTE_ORDER__ == __ORDER_LITTLE_ENDIAN__ && !defined(JSON_NUM_PORTABLE)
#define JSON_NUM_EIGHT_DIGITS 1

/* Whether each of the 8 bytes of v is an ASCII digit: the high bit of a byte
 * comes up in v + 0x46 for a byte above '9' and in v - 0x30 for one below '0'
 * (a borrow from a lower byte also flags it, and then that lower byte is not
 * a digit either). */
static inline int isEightDigits(uint64_t v) {
    return (((v + 0x4646464646464646ULL) | (v - 0x3030303030303030ULL)) & 0x8080808080808080ULL) == 0;
}

/* Value of the 8 ASCII digits in v, the first digit in the lowest byte. Adds
 * neighbours pairwise: digits to 2-digit numbers (one per 16 bits), then the
 * four of them to one number with two multiplications. */
static inline uint64_t parseEightDigits(uint64_t v) {
    const uint64_t mask = 0x000000FF000000FFULL;
    const uint64_t mul1 = 100 + (1000000ULL << 32);
    const uint64_t mul2 = 1 + (10000ULL << 32);
    v -= 0x3030303030303030ULL;
    v = v * 10 + (v >> 8);
    return (((v & mask) * mul1) + (((v >> 16) & mask) * mul2)) >> 32;
}
#endif

/* Number of decimal digits of v, 1 for zero. With b the bit length of v,
 * t = floor(b * log10(2)) is that number or one less. */
static inline int countDigits(uint64_t v) {
    /* 10^t, except that the first entry is 0 so that v < 10 counts one digit. */
    static const uint64_t tenTo[20] = {0ULL, 10ULL, 100ULL, 1000ULL, 10000ULL, 100000ULL, 1000000ULL, 10000000ULL,
                                       100000000ULL, 1000000000ULL, 10000000000ULL, 100000000000ULL,
                                       1000000000000ULL, 10000000000000ULL, 100000000000000ULL,
                                       1000000000000000ULL, 10000000000000000ULL, 100000000000000000ULL,
                                       1000000000000000000ULL, 10000000000000000000ULL};
    int t = ((64 - clz64(v | 1)) * 1233) >> 12;
    return t + (v >= tenTo[t]);
}

/* Writes v < 10^8 as exactly 8 digits. */
static inline void writeEightDigits(char *p, uint32_t v) {
    uint32_t hi = v / 10000, lo = v - hi * 10000;
    uint32_t a = hi / 100, b = lo / 100;
    memcpy(p, JSON_DIGIT_PAIRS + 2 * a, 2);
    memcpy(p + 2, JSON_DIGIT_PAIRS + 2 * (hi - a * 100), 2);
    memcpy(p + 4, JSON_DIGIT_PAIRS + 2 * b, 2);
    memcpy(p + 6, JSON_DIGIT_PAIRS + 2 * (lo - b * 100), 2);
}

/* Writes v < 10^nd as exactly nd digits, zero-padded on the left. */
static inline void writeDigits(char *p, uint64_t v, int nd) {
    char *end = p + nd;
    for (; nd >= 8; nd -= 8) {
        uint64_t q = v / 100000000;
        writeEightDigits(end -= 8, (uint32_t)(v - q * 100000000));
        v = q;
    }
    for (; nd >= 2; nd -= 2) {
        uint64_t q = v / 100;
        memcpy(end -= 2, JSON_DIGIT_PAIRS + 2 * (v - q * 100), 2);
        v = q;
    }
    if (nd) *--end = (char)('0' + v);
}

static inline double bitsToDouble(uint64_t bits) {
    double d;
    memcpy(&d, &bits, sizeof(d));
    return d;
}

static inline uint64_t doubleToBits(double d) {
    uint64_t bits;
    memcpy(&bits, &d, sizeof(bits));
    return bits;
}

/* ----------------------------------------------------------------------------
 * Double to shortest decimal (Schubfach)
 * ------------------------------------------------------------------------- */

/* With g = {ghi, glo} the table entry for 10^-k and cp = c' << h, the exact
 * value wanted is x = c' * 2^q / 10^k and cp * g = x * 2^128 + delta, where
 * 0 <= delta < cp < 2^59 because g is at most one unit too large. Returns x
 * rounded to odd: floor(x), with the low bit set when x is not an integer.
 *
 * gen_pow10.py proves that for every double, x is either an integer or has
 * 2^-69 <= frac(x) < 1 - 2^-69. So delta never carries into the integer part,
 * and the fraction of cp * g is below 2^59 / 2^128 exactly when x is an
 * integer. */
static inline uint64_t roundToOdd(uint64_t ghi, uint64_t glo, uint64_t cp) {
    uint64_t xhi, yhi;
    uint64_t xlo = mul64(glo, cp, &xhi);
    uint64_t ylo = mul64(ghi, cp, &yhi);
    ylo += xhi;
    yhi += ylo < xhi;
    return yhi | ((ylo | (xlo >> 59)) != 0);
}

/* 5^-i modulo 2^64, for dividesPow10(). */
#define JSON_INV_5_POW_8 0xC767074B22E90E21ULL
#define JSON_INV_5_POW_4 0xD288CE703AFB7E91ULL
#define JSON_INV_5_POW_2 0x8F5C28F5C28F5C29ULL
#define JSON_INV_5_POW_1 0xCCCCCCCCCCCCCCCDULL
_Static_assert((uint64_t)(JSON_INV_5_POW_8 * 390625ULL) == 1, "inverse of 5^8");
_Static_assert((uint64_t)(JSON_INV_5_POW_4 * 625ULL) == 1, "inverse of 5^4");
_Static_assert((uint64_t)(JSON_INV_5_POW_2 * 25ULL) == 1, "inverse of 5^2");
_Static_assert((uint64_t)(JSON_INV_5_POW_1 * 5ULL) == 1, "inverse of 5");

/* If tenToI = 10^i divides *v, divides it and returns 1. Multiplying by the
 * inverse of 5^i modulo 2^64 maps the multiples of 5^i, and nothing else, onto
 * [0, UINT64_MAX / 5^i], each to its quotient. Rotating right by i bits then
 * divides by 2^i when the low i bits are zero and otherwise yields at least
 * 2^(64-i). So the result is at most UINT64_MAX / 10^i exactly for the
 * multiples of 10^i, and is then the quotient. */
static inline int dividesPow10(uint64_t *v, uint64_t inv5, int i, uint64_t tenToI) {
    uint64_t r = *v * inv5;
    r = (r >> i) | (r << (64 - i));
    if (r > UINT64_MAX / tenToI) return 0;
    *v = r;
    return 1;
}

/* Shortest decimal of the finite, positive double with the given bits: returns
 * dec and sets *decExp so that the value reads dec * 10^(*decExp). dec has at
 * most 17 digits. It has no trailing zeros, except for a whole number below
 * 2^53, which comes back as itself with *decExp == 0. */
static uint64_t doubleToDecimal(uint64_t bits, int *decExp) {
    uint64_t frac = bits & (JSON_DBL_HIDDEN - 1);
    int bexp = (int)(bits >> 52);
    uint64_t c;
    int q;

    /* The value is c * 2^q. */
    if (bexp != 0) {
        c = frac | JSON_DBL_HIDDEN;
        q = bexp - 1075;
    } else {
        c = frac;
        q = -1074;
    }

    /* Whole numbers below 2^53 have an ulp of at most 1, so their own digits
     * are the shortest. */
    if (q <= 0 && q >= -52 && (c & ((1ULL << -q) - 1)) == 0) {
        *decExp = 0;
        return c >> -q;
    }

    /* The rounding interval of v reaches half way to each neighbour. Below a
     * power of two the lower neighbour is half as far (the irregular case). In
     * units of 2^(q-2): v is cb, the interval is [cbl, cbr]. Its ends read back
     * as v only if c is even (round half to even). */
    int irregular = (frac == 0 && bexp > 1);
    uint64_t odd = c & 1;
    uint64_t cb = 4 * c;
    uint64_t cbl = cb - 2 + (uint64_t)irregular;
    uint64_t cbr = cb + 2;

    int k = irregular ? floorLog10ThreeQuartersPow2(q) : floorLog10Pow2(q);
    int h = q + floorLog2Pow10(-k) + 1; /* 1 <= h <= 4 */
    const uint64_t *g = JSON_POW10[-k - JSON_POW10_MIN];

    /* The same three points in units of 10^k / 4, rounded to odd. Rounding to
     * odd keeps every comparison with an even integer exact. */
    uint64_t vbl = roundToOdd(g[0], g[1], cbl << h);
    uint64_t vb = roundToOdd(g[0], g[1], cb << h);
    uint64_t vbr = roundToOdd(g[0], g[1], cbr << h);
    uint64_t lower = vbl + odd;
    uint64_t upper = vbr - odd;

    /* s = floor(v / 10^k). First try the multiples of 10^(k+1) around v. At
     * most one of them is in the interval. */
    uint64_t s = vb >> 2;
    uint64_t sp = s / 10;
    int uin = lower <= 40 * sp;
    int win = 40 * sp + 40 <= upper;
    if (uin != win) {
        /* Drop the trailing zeros: there are at most 16. */
        uint64_t dec = sp + (uint64_t)win;
        k++;
        while (dividesPow10(&dec, JSON_INV_5_POW_8, 8, 100000000)) k += 8;
        if (dividesPow10(&dec, JSON_INV_5_POW_4, 4, 10000)) k += 4;
        if (dividesPow10(&dec, JSON_INV_5_POW_2, 2, 100)) k += 2;
        if (dividesPow10(&dec, JSON_INV_5_POW_1, 1, 10)) k += 1;
        *decExp = k;
        return dec;
    }

    /* Then s and s + 1. At least one of them is in the interval. */
    *decExp = k;
    uin = lower <= 4 * s;
    win = 4 * s + 4 <= upper;
    if (uin != win) return s + (uint64_t)win;

    /* Both are: take the closer, and the even one on a tie. */
    uint64_t mid = 4 * s + 2;
    return s + (uint64_t)(vb > mid || (vb == mid && (s & 1)));
}

/* Lays out dec * 10^k the way ECMAScript's Number::toString does, plus ".0"
 * where that would print no fraction. Returns the end of the text. */
static char *writeCanonical(char *p, uint64_t dec, int k) {
    int nd = countDigits(dec);
    int n = nd + k; /* The value is 0.DIGITS * 10^n. */

    if (k >= 0 && n <= 21) {
        /* DIGITS000.0 */
        writeDigits(p, dec, nd);
        p += nd;
        if (k) {
            memset(p, '0', (size_t)k);
            p += k;
        }
        *p++ = '.';
        *p++ = '0';
    } else if (n > 0 && n <= 21) {
        /* DIG.ITS */
        writeDigits(p + 1, dec, nd);
        memmove(p, p + 1, (size_t)n);
        p[n] = '.';
        p += nd + 1;
    } else if (n > -6 && n <= 0) {
        /* 0.000DIGITS */
        *p++ = '0';
        *p++ = '.';
        if (n) {
            memset(p, '0', (size_t)-n);
            p += -n;
        }
        writeDigits(p, dec, nd);
        p += nd;
    } else {
        /* D.IGITSe+XX */
        int e = n - 1;
        writeDigits(p + 1, dec, nd);
        p[0] = p[1];
        if (nd > 1) {
            p[1] = '.';
            p += nd + 1;
        } else {
            p++;
        }
        *p++ = 'e';
        *p++ = e < 0 ? '-' : '+';
        e = e < 0 ? -e : e;
        if (e >= 100) {
            *p++ = (char)('0' + e / 100);
            e %= 100;
            memcpy(p, JSON_DIGIT_PAIRS + 2 * e, 2);
            p += 2;
        } else if (e >= 10) {
            memcpy(p, JSON_DIGIT_PAIRS + 2 * e, 2);
            p += 2;
        } else {
            *p++ = (char)('0' + e);
        }
    }
    return p;
}

int jsonDoublePrint(double d, char *buf) {
    uint64_t bits = doubleToBits(d);
    char *p = buf;
    int k;

    if ((bits & ~JSON_DBL_SIGN) >= JSON_DBL_INF) {
        /* Not a finite double, which the caller promised. Print what
         * Number::toString would, so that at least the buffer is respected. */
        if ((bits & ~JSON_DBL_SIGN) > JSON_DBL_INF) {
            memcpy(p, "NaN", 3);
            return 3;
        }
        if (bits & JSON_DBL_SIGN) *p++ = '-';
        memcpy(p, "Infinity", 8);
        return (int)(p + 8 - buf);
    }
    /* Without a branch: the sign of real data is hard to predict. Every path
     * below writes at least one byte at p. */
    *p = '-';
    p += bits >> 63;
    bits &= ~JSON_DBL_SIGN;
    if (bits == 0) {
        memcpy(p, "0.0", 3);
        return (int)(p + 3 - buf);
    }
    uint64_t dec = doubleToDecimal(bits, &k);
    return (int)(writeCanonical(p, dec, k) - buf);
}

int jsonDoublePrintFixed(double d, int frac, char *buf) {
    uint64_t bits = doubleToBits(d);
    uint64_t mag = bits & ~JSON_DBL_SIGN;
    char *p = buf;
    int k;

    if (frac < 1 || frac > 15 || mag >= JSON_DBL_INF) return 0;
    if (mag == 0) {
        if (bits & JSON_DBL_SIGN) *p++ = '-';
        *p++ = '0';
        *p++ = '.';
        memset(p, '0', (size_t)frac);
        return (int)(p + frac - buf);
    }

    uint64_t dec = doubleToDecimal(mag, &k);
    int nd = countDigits(dec);
    int n = nd + k; /* The value is 0.DIGITS * 10^n. */

    /* The text has -k fractional digits before padding. After padding it has
     * n + frac significant digits, which also rules out |d| >= 1e15 (n > 15). */
    if (-k > frac || n + frac > 15) return 0;

    if (bits & JSON_DBL_SIGN) *p++ = '-';
    if (k >= 0) {
        /* DIGITS000.000 */
        writeDigits(p, dec, nd);
        p += nd;
        memset(p, '0', (size_t)k);
        p += k;
        *p++ = '.';
        memset(p, '0', (size_t)frac);
        p += frac;
    } else if (n > 0) {
        /* DIG.ITS00 */
        writeDigits(p + 1, dec, nd);
        memmove(p, p + 1, (size_t)n);
        p[n] = '.';
        p += nd + 1;
        memset(p, '0', (size_t)(frac + k));
        p += frac + k;
    } else {
        /* 0.000DIGITS00 */
        *p++ = '0';
        *p++ = '.';
        memset(p, '0', (size_t)-n);
        p += -n;
        writeDigits(p, dec, nd);
        p += nd;
        memset(p, '0', (size_t)(frac + k));
        p += frac + k;
    }
    return (int)(p - buf);
}

int jsonInt64Print(int64_t v, char *buf) {
    uint64_t u = v < 0 ? 0 - (uint64_t)v : (uint64_t)v;
    int nd = countDigits(u);
    char *p = buf;

    if (v < 0) *p++ = '-';
    writeDigits(p, u, nd);
    return (int)(p + nd - buf);
}

/* ----------------------------------------------------------------------------
 * Decimal to double
 * ------------------------------------------------------------------------- */

/* Rounds w * 10^e to the nearest double (ties to even), for w != 0 and
 * JSON_POW10_MIN <= e <= 308. Returns 1 and stores the bits of the result,
 * which may be infinity or anything at or above it when the value overflows.
 * Returns 0 without an answer when the rounding cannot be decided here.
 *
 * Shift w left to 64 bits and let beta be 10^e scaled into [2^127, 2^128), so
 * that the table entry is g = ceil(beta). The exact value, scaled, is
 * X = w * beta < 2^192, and P = w * g satisfies P - 2^64 < X <= P. The
 * significand is the top 53 bits of P (fewer for a subnormal), and the
 * rounding boundaries are the multiples of half its last place. If P is at
 * least 2^64 above the boundary below it, X is strictly above that boundary as
 * well and below the next: same significand, same rounding direction, no tie.
 * Otherwise X = P when the table entry is exact, and in every other case we
 * give up. */
static int decimalToBits(uint64_t w, int e, uint64_t *bits) {
    const uint64_t *g = JSON_POW10[e - JSON_POW10_MIN];
    int lz = clz64(w);
    uint64_t p0, p1, p2, carry;

    /* P = p2 * 2^128 + p1 * 2^64 + p0, with 2^190 <= P < 2^192. */
    w <<= lz;
    p0 = mul64(w, g[1], &carry);
    p1 = mul64(w, g[0], &p2);
    p1 += carry;
    p2 += p1 < carry;

    /* The significand is p2 >> sh: 53 bits for a normal double, whose biased
     * exponent is then bexp. A subnormal keeps fewer bits. */
    int sh = 10 + (int)(p2 >> 63);
    int bexp = floorLog2Pow10(e) + 1 + sh - lz + 1075;
    if (bexp <= 0) {
        sh += 1 - bexp;
        bexp = 1;
        if (sh > 63) return 0; /* Below half the smallest subnormal, or close. */
    }

    uint64_t m = p2 >> sh;
    uint64_t half = (p2 >> (sh - 1)) & 1;
    uint64_t below = (p2 & ((1ULL << (sh - 1)) - 1)) | p1; /* Bits of P under the half bit and over 2^64. */
    if (below == 0) {
        if (e < 0 || e > JSON_POW10_EXACT_MAX) return 0;
        below = p0;
    }
    m += half & ((below != 0) | m);

    /* For a normal double m carries the hidden bit, which bumps the exponent
     * field from bexp - 1 to bexp. A subnormal has bexp == 1 and no hidden bit.
     * A carry out of m lands in the exponent, which is what it should do. */
    *bits = ((uint64_t)(bexp - 1) << 52) + m;
    return 1;
}

/* Arbitrary precision decimal for the slow path: the value is
 * 0.d[0]d[1]...d[nd-1] * 10^dp, with d[0] != 0 and d[nd-1] != 0. When
 * truncated is set the true value is larger, by less than one unit of the
 * last digit the buffer can hold.
 *
 * 800 digits are enough. The decision only ever compares the value with the
 * exact midpoint of two adjacent doubles, scaled by a power of two. Such a
 * midpoint has at most 768 significant digits, and no more than that plus a
 * few at any step on the way, so it is never truncated. Every step is a
 * monotonic rounding down that keeps such values intact. Hence the stored
 * value is on the same side of the midpoint as the true one, and when it
 * equals the midpoint, `truncated` tells whether the true value is above it. */
#define JSON_DECIMAL_DIGITS 800
#define JSON_DECIMAL_MAX_SHIFT 60

typedef struct jsonDecimal {
    int nd;
    int dp;
    int truncated;
    uint8_t d[JSON_DECIMAL_DIGITS];
} jsonDecimal;

static void decimalTrim(jsonDecimal *a) {
    while (a->nd > 0 && a->d[a->nd - 1] == 0) a->nd--;
}

/* a /= 2^k, 1 <= k <= JSON_DECIMAL_MAX_SHIFT, a != 0. Long division, one digit
 * at a time, with the running remainder n < 2^k. */
static void decimalShiftRight(jsonDecimal *a, int k) {
    uint64_t mask = (1ULL << k) - 1;
    uint64_t n = 0;
    int r = 0, w = 0;

    /* Take digits until the first quotient digit is nonzero. */
    while ((n >> k) == 0) {
        n = n * 10 + (r < a->nd ? a->d[r] : 0);
        r++;
    }
    a->dp -= r - 1;

    for (; r < a->nd; r++) {
        a->d[w++] = (uint8_t)(n >> k);
        n = (n & mask) * 10 + a->d[r];
    }
    while (n != 0) {
        uint8_t digit = (uint8_t)(n >> k);
        n = (n & mask) * 10;
        if (w < JSON_DECIMAL_DIGITS) {
            a->d[w++] = digit;
        } else if (digit != 0) {
            a->truncated = 1;
        }
    }
    a->nd = w;
    decimalTrim(a);
}

/* a *= 2^k, 1 <= k <= JSON_DECIMAL_MAX_SHIFT, a != 0. Schoolbook
 * multiplication from the last digit up. */
static void decimalShiftLeft(jsonDecimal *a, int k) {
    /* The product has `grow` or `grow - 1` more digits than a:
     * grow = floor(k * log10(2)) + 1. */
    int grow = ((k * 1233) >> 12) + 1;
    int r = a->nd - 1;
    int w = a->nd + grow - 1;
    uint64_t n = 0;

    for (; w >= 0; w--, r--) {
        if (r >= 0) n += (uint64_t)a->d[r] << k;
        uint64_t quo = n / 10;
        uint8_t digit = (uint8_t)(n - quo * 10);
        if (w < JSON_DECIMAL_DIGITS) {
            a->d[w] = digit;
        } else if (digit != 0) {
            a->truncated = 1;
        }
        n = quo;
    }
    a->nd += grow;
    if (a->nd > JSON_DECIMAL_DIGITS) a->nd = JSON_DECIMAL_DIGITS;
    a->dp += grow;
    if (a->d[0] == 0) {
        a->nd--;
        a->dp--;
        memmove(a->d, a->d + 1, (size_t)a->nd);
    }
    decimalTrim(a);
}

/* Bits a power of two may have and still not exceed 10^i: floor(i * log2(10)),
 * capped at the largest shift. */
static inline int decimalShiftFor(int i) {
    int k = (i * 217706) >> 16;
    return k > JSON_DECIMAL_MAX_SHIFT ? JSON_DECIMAL_MAX_SHIFT : k;
}

/* Rounds the decimal number written in [mant, mantEnd), an unsigned digit
 * string with at most one '.', times 10^e, to the nearest double (ties to
 * even). Returns its bits, JSON_DBL_INF on overflow. Always exact. */
static uint64_t decimalSlowToBits(const char *mant, const char *mantEnd, int64_t e) {
    jsonDecimal a;
    int64_t ndigits = 0;
    int exp2 = 0;

    a.nd = 0;
    a.truncated = 0;
    while (mant < mantEnd && (*mant == '0' || *mant == '.')) {
        if (*mant == '.') e -= mantEnd - mant - 1;
        mant++;
    }
    for (; mant < mantEnd; mant++) {
        if (*mant == '.') {
            e -= mantEnd - mant - 1;
            continue;
        }
        if (a.nd < JSON_DECIMAL_DIGITS) {
            a.d[a.nd++] = (uint8_t)(*mant - '0');
        } else if (*mant != '0') {
            a.truncated = 1;
        }
        ndigits++;
    }
    decimalTrim(&a);
    if (a.nd == 0) return 0;

    /* The value is in [10^(dp-1), 10^dp). The largest double is below 10^309
     * and half the smallest one is above 10^-324. */
    if (ndigits + e > 310) return JSON_DBL_INF;
    if (ndigits + e < -330) return 0;
    a.dp = (int)(ndigits + e);

    /* Scale by powers of two into [1/2, 1): value = a * 2^exp2. */
    while (a.dp > 0) {
        int k = decimalShiftFor(a.dp);
        decimalShiftRight(&a, k);
        exp2 += k;
    }
    while (a.dp < 0 || a.d[0] < 5) {
        int k = a.dp < 0 ? decimalShiftFor(-a.dp) : 1;
        decimalShiftLeft(&a, k);
        exp2 -= k;
    }

    /* A normal double is (a * 2^53) * 2^(exp2 - 53), biased exponent
     * exp2 + 1022. A subnormal has its last place fixed at 2^-1074. */
    int bexp = exp2 + 1022;
    int shift = 53;
    if (bexp > 2046) return JSON_DBL_INF;
    if (bexp < 1) {
        shift -= 1 - bexp;
        bexp = 1;
    }
    if (shift > 0) decimalShiftLeft(&a, shift);
    if (shift < 0) decimalShiftRight(&a, -shift);

    /* Round to an integer, ties to even. */
    uint64_t m = 0;
    for (int i = 0; i < a.dp; i++) m = m * 10 + (i < a.nd ? a.d[i] : 0);
    if (a.dp >= 0 && a.dp < a.nd) {
        uint8_t next = a.d[a.dp];
        int exactHalf = (next == 5 && a.dp + 1 == a.nd && !a.truncated);
        if (next > 5 || (next == 5 && (!exactHalf || (m & 1)))) m++;
    }
    return ((uint64_t)(bexp - 1) << 52) + m;
}

/* The powers of ten that are exact doubles. */
static const double pow10Double[] = {1e0, 1e1, 1e2, 1e3, 1e4, 1e5, 1e6, 1e7, 1e8, 1e9, 1e10, 1e11,
                                     1e12, 1e13, 1e14, 1e15, 1e16, 1e17, 1e18, 1e19, 1e20, 1e21, 1e22};

double jsonDoubleParse(const char *s, size_t n, int *overflow) {
    const char *p = s, *end = s + n;
    const char *mant, *mantEnd, *dot = NULL;
    uint64_t sign = 0, w = 0, bits = 0, bits2 = 0;
    int64_t decExp = 0;
    int truncated = 0;

    *overflow = 0;
    if (p < end && *p == '-') {
        sign = JSON_DBL_SIGN;
        p++;
    }

    /* Read every mantissa digit into w. It wraps around when there are more
     * than 19 of them, which is put right below. */
    mant = p;
    while (p < end && isDigit(*p)) w = w * 10 + (uint64_t)(*p++ - '0');
    if (p < end && *p == '.') {
        dot = p++;
#ifdef JSON_NUM_EIGHT_DIGITS
        while (end - p >= 8) {
            uint64_t v;
            memcpy(&v, p, 8);
            if (!isEightDigits(v)) break;
            w = w * 100000000 + parseEightDigits(v);
            p += 8;
        }
#endif
        while (p < end && isDigit(*p)) w = w * 10 + (uint64_t)(*p++ - '0');
    }
    mantEnd = p;

    if (p < end && (*p == 'e' || *p == 'E')) {
        int negative = 0;
        p++;
        if (p < end && (*p == '-' || *p == '+')) negative = (*p++ == '-');
        for (; p < end && isDigit(*p); p++) {
            /* Saturate: no text is long enough to bring 10^17 back in range. */
            if (decExp < 100000000000000000LL) decExp = decExp * 10 + (*p - '0');
        }
        if (negative) decExp = -decExp;
    }

    /* The value is w * 10^e. */
    int64_t e = decExp - (dot ? mantEnd - dot - 1 : 0);
    if (mantEnd - mant - (dot != NULL) > 19) {
        const char *z = mant;
        while (z < mantEnd && (*z == '0' || *z == '.')) z++;
        int64_t ndigits = mantEnd - z - (dot != NULL && z < dot);
        if (ndigits > 19) {
            /* Keep 19 significant digits: the value is in [w, w + 1) * 10^e. */
            w = 0;
            for (int i = 0; i < 19; z++) {
                if (*z == '.') continue;
                w = w * 10 + (uint64_t)(*z - '0');
                i++;
            }
            e += ndigits - 19;
            truncated = 1;
        }
    }

    if (w == 0) return bitsToDouble(sign);

#if defined(FLT_EVAL_METHOD) && FLT_EVAL_METHOD == 0
    /* Clinger's fast path: w and 10^|e| are exact doubles, so one IEEE
     * operation rounds once. Skipped where doubles are evaluated in a wider
     * format; the paths below do not use floating point at all. */
    if (w <= (1ULL << 53) && e >= -22 && e <= 22 && !truncated) {
        double d = (double)w;
        d = e < 0 ? d / pow10Double[-e] : d * pow10Double[e];
        return sign ? -d : d;
    }
#else
    (void)pow10Double;
#endif

    if (e > 308) {
        bits = JSON_DBL_INF; /* w >= 1 */
    } else if (e < JSON_POW10_MIN) {
        bits = 0; /* w + 1 <= 10^19, and 10^-324 is below half the smallest subnormal. */
    } else if (!decimalToBits(w, (int)e, &bits) ||
               (truncated && (!decimalToBits(w + 1, (int)e, &bits2) || bits2 != bits))) {
        bits = decimalSlowToBits(mant, mantEnd, decExp);
    }

    if (bits >= JSON_DBL_INF) {
        bits = JSON_DBL_INF;
        *overflow = 1;
    }
    return bitsToDouble(bits | sign);
}

double jsonDoubleFromDecimal(uint64_t mantissa, int exp10, int negative) {
    const uint64_t sign = negative ? JSON_DBL_SIGN : 0;
    uint64_t bits;

    if (mantissa == 0) return bitsToDouble(sign);

#if defined(FLT_EVAL_METHOD) && FLT_EVAL_METHOD == 0
    /* Clinger's fast path, as in jsonDoubleParse(). */
    if (mantissa <= (1ULL << 53) && exp10 >= -22 && exp10 <= 22) {
        double d = (double)mantissa;
        d = exp10 < 0 ? d / pow10Double[-exp10] : d * pow10Double[exp10];
        return negative ? -d : d;
    }
#endif

    if (exp10 > 308) {
        bits = JSON_DBL_INF; /* mantissa >= 1 */
    } else if (exp10 < JSON_POW10_MIN) {
        bits = 0; /* mantissa < 1.85e19: the value is below 1.85e-324, under half the smallest subnormal. */
    } else if (!decimalToBits(mantissa, exp10, &bits)) {
        /* The exact path reads digits. This is the only place they are made. */
        char digits[20];
        int nd = countDigits(mantissa);
        writeDigits(digits, mantissa, nd);
        bits = decimalSlowToBits(digits, digits + nd, exp10);
    }
    if (bits > JSON_DBL_INF) bits = JSON_DBL_INF;
    return bitsToDouble(bits | sign);
}
