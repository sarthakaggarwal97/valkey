/* json_num.c -- number text for the built-in JSON module.
 *
 * Printing uses Schubfach (Raffaello Giulietti, "The Schubfach way to render
 * doubles", 2020). For a double v = c * 2^q it picks the decimal exponent k
 * with 10^k <= W < 10^(k+1), W being the width of the rounding interval of v
 * (2^q, or 3/4 of it just above a power of two), so that the interval holds at
 * most one multiple of 10^(k+1) and at least one multiple of 10^k. If the
 * multiple of 10^(k+1) is there it is the shortest text. Otherwise the answer
 * is whichever of floor(v / 10^k) and floor(v / 10^k) + 1 lies in the interval,
 * and the closer one (ties to even) when both do. The result is the shortest
 * digit string that reads back as v and, among those, the closest to v: the
 * digits of ECMAScript's Number::toString and of Python's repr().
 *
 * Parsing takes the first 19 significant digits as an integer w and a decimal
 * exponent e, then tries in order:
 *
 *   1. Clinger's fast path: w <= 2^53 and |e| <= 22, one exact multiplication
 *      or division of doubles.
 *   2. A 64x128-bit multiplication of w by the table entry for 10^e, in the
 *      manner of Eisel-Lemire. The table entry is at most one unit too large,
 *      so the product is too large by less than 2^64; unless it lies that close
 *      above a rounding boundary the rounded result is certain. See
 *      decimalToBits(). When digits were dropped, w and w + 1 must agree.
 *   3. Exact decimal arithmetic on up to 800 digits, shifted by powers of two
 *      until the integer part is the significand. See decimalSlowToBits().
 *      This path is ours as well: strtod() is not used anywhere.
 *
 * The table. JSON_POW10[e - JSON_POW10_MIN] is the 128-bit integer
 * g = ceil(10^e * 2^(127 - L)), L = floor(log2(10^e)), as {high, low} words:
 * 10^e rounded up to 128 significant bits, 2^127 <= g < 2^128. Entries for
 * 0 <= e <= JSON_POW10_EXACT_MAX are exact. The printer needs
 * -292 <= e <= 324 and the parser -342 <= e <= 308, hence 667 entries
 * (10672 bytes). The table is generated by tests/num/gen_pow10.py, which also
 * re-proves, in exact arithmetic, the logarithm formulas below and the bound
 * that roundToOdd() depends on. Run `make -C tests/num check-table` to verify
 * that this file still holds the generated table.
 *
 * Nothing here allocates, touches global mutable state or depends on the
 * locale, and every function is safe to call from any thread. */

